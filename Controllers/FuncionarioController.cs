using System.Globalization;
using System.Security.Claims;
using System.Text;
using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Rendering;
using Microsoft.EntityFrameworkCore;
using SisHospedar.Data;
using SisHospedar.Filters;
using SisHospedar.Models;

namespace SisHospedar.Controllers
{
    // PT: Gerencia a equipe do hotel. Restrito a Administrador/Gerente.
    // EN: Manages hotel staff. Restricted to Administrador/Gerente roles.
    [RequerCargo(CargoFuncionario.Administrador, CargoFuncionario.Gerente)]
    public class FuncionarioController : Controller
    {
        private readonly AppDbContext _context;
        private readonly UserManager<Funcionario> _userManager;

        public FuncionarioController(AppDbContext context, UserManager<Funcionario> userManager)
        {
            _context = context;
            _userManager = userManager;
        }

        public async Task<IActionResult> Index()
        {
            return View(await _context.Funcionarios.OrderBy(f => f.Nome).ToListAsync());
        }

        public async Task<IActionResult> Details(int? id)
        {
            if (id == null) return NotFound();
            var funcionario = await _context.Funcionarios
                .Include(f => f.Hospede)
                .FirstOrDefaultAsync(f => f.FuncionarioId == id);
            if (funcionario == null) return NotFound();
            return View(funcionario);
        }

        public IActionResult Create()
        {
            CarregarListaHospedes();
            return View();
        }

        // PT: Recebe a senha em texto puro APENAS neste parâmetro de entrada — o
        //     UserManager<Funcionario> (Identity) é quem faz o hash e persiste, via
        //     EntityUserStore; a senha original nunca é salva nem logada.
        //     HospedeId é opcional: só vincula se o novo funcionário já tiver conta de hóspede.
        //     Login não vem do form — é sempre gerado por GerarLoginUnicoAsync (só o
        //     hóspede escolhe o próprio login, em ClienteController.Registrar).
        // EN: Receives the plain-text password ONLY as this input parameter —
        //     UserManager<Funcionario> (Identity) is what hashes and persists it, via
        //     EntityUserStore; the original password is never saved or logged.
        //     HospedeId is optional: only links if the new employee already has a guest account.
        //     Login doesn't come from the form — it's always generated by
        //     GerarLoginUnicoAsync (only the guest picks their own login, in
        //     ClienteController.Registrar).
        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> Create([Bind("Nome,Cargo,Email,HospedeId")] Funcionario funcionario, string senha)
        {
            ModelState.Remove(nameof(Funcionario.SenhaHash));
            ModelState.Remove(nameof(Funcionario.Login));

            if (ModelState.IsValid)
            {
                funcionario.Login = await GerarLoginUnicoAsync(funcionario.Nome);
                var resultado = await _userManager.CreateAsync(funcionario, senha);
                if (resultado.Succeeded)
                {
                    TempData["Sucesso"] = $"Funcionário cadastrado com sucesso. Login gerado: {funcionario.Login}";
                    return RedirectToAction(nameof(Index));
                }
                foreach (var erro in resultado.Errors)
                    ModelState.AddModelError("senha", erro.Description);
            }
            CarregarListaHospedes(funcionario.HospedeId);
            return View(funcionario);
        }

        // PT: Gera o login a partir do nome, tentando nesta ordem até achar um livre
        //     (checando colisão em Funcionarios E Hospedes, mesmo "namespace" de login):
        //       1. primeiro.segundo               (ex.: "Luan Santos" -> luan.santos)
        //       2. primeiro.terceiro, se existir   (quando o padrão 1 colide e há um
        //                                            terceiro nome pra diferenciar)
        //       3. segundo.primeiro                (inverte quando só há dois nomes e o
        //                                            padrão 1 já colidiu — ex.: um
        //                                            funcionário e um hóspede chamados
        //                                            "Luan Santos" viram luan.santos e
        //                                            santos.luan, não luan.santos2)
        //       4. sufixo numérico                 (rede de segurança final, se mesmo
        //                                            assim tudo colidir)
        // EN: Generates the login from the name, trying in this order until one is free
        //     (checking collisions in both Funcionarios and Hospedes, same login
        //     "namespace"):
        //       1. first.second                    (e.g. "Luan Santos" -> luan.santos)
        //       2. first.third, if present          (when pattern 1 collides and there's
        //                                            a third name to disambiguate with)
        //       3. second.first                     (inverted, when there are only two
        //                                            names and pattern 1 already
        //                                            collided — e.g. an employee and a
        //                                            guest both named "Luan Santos" end
        //                                            up as luan.santos and santos.luan,
        //                                            not luan.santos2)
        //       4. numeric suffix                   (final safety net, if everything
        //                                            above still collides)
        private async Task<string> GerarLoginUnicoAsync(string nome)
        {
            var partes = nome.Trim().Split(' ', StringSplitOptions.RemoveEmptyEntries)
                .Select(RemoverAcentos).ToArray();

            if (partes.Length == 1) return await PrimeiroLivreAsync(partes[0]);

            var primeiro = partes[0];
            var segundo = partes[1];

            var candidatos = new List<string> { $"{primeiro}.{segundo}" };
            if (partes.Length >= 3) candidatos.Add($"{primeiro}.{partes[2]}");
            candidatos.Add($"{segundo}.{primeiro}");

            foreach (var candidato in candidatos)
                if (!await LoginExisteAsync(candidato))
                    return candidato;

            return await PrimeiroLivreAsync(candidatos[^1]);
        }

        private async Task<bool> LoginExisteAsync(string login) =>
            await _context.Funcionarios.AnyAsync(f => f.Login == login) ||
            await _context.Hospedes.AnyAsync(h => h.Login == login);

        private async Task<string> PrimeiroLivreAsync(string loginBase)
        {
            var login = loginBase;
            var sufixo = 1;
            while (await LoginExisteAsync(login))
            {
                sufixo++;
                login = $"{loginBase}{sufixo}";
            }
            return login;
        }

        private static string RemoverAcentos(string texto)
        {
            var normalizado = texto.Normalize(NormalizationForm.FormD);
            var semAcento = new StringBuilder();
            foreach (var c in normalizado)
                if (CharUnicodeInfo.GetUnicodeCategory(c) != UnicodeCategory.NonSpacingMark)
                    semAcento.Append(c);
            return semAcento.ToString().Normalize(NormalizationForm.FormC).ToLowerInvariant();
        }

        public async Task<IActionResult> Delete(int? id)
        {
            if (id == null) return NotFound();
            var funcionario = await _context.Funcionarios.FirstOrDefaultAsync(f => f.FuncionarioId == id);
            if (funcionario == null) return NotFound();
            return View(funcionario);
        }

        [HttpPost, ActionName("Delete")]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> DeleteConfirmed(int id)
        {
            var funcionario = await _context.Funcionarios.FindAsync(id);
            if (funcionario == null) return RedirectToAction(nameof(Index));

            // PT: Antes disto era possível excluir a PRÓPRIA conta enquanto logado. A conta
            //     sumia, o cookie continuava valendo apontando para um funcionário que não
            //     existe mais, e a pessoa ficava num limbo: autenticada para o handler de
            //     cookie, inexistente para a aplicação.
            // EN: Before this it was possible to delete your OWN account while logged in. The
            //     account vanished, the cookie stayed valid pointing at an employee who no
            //     longer exists, and the person ended up in limbo: authenticated as far as
            //     the cookie handler is concerned, nonexistent to the application.
            var meuId = int.Parse(User.FindFirstValue(ClaimTypes.NameIdentifier)!);
            if (funcionario.FuncionarioId == meuId)
            {
                TempData["Erro"] = "Você não pode excluir a sua própria conta. Peça a outro Administrador ou Gerente.";
                return RedirectToAction(nameof(Index));
            }

            // PT: NÃO existe aqui uma regra separada de "não excluir o último gestor", e a
            //     ausência é deliberada. Cheguei a escrever uma, e o teste mostrou que ela
            //     nunca dispararia: só Administrador e Gerente alcançam esta tela (ver
            //     [RequerCargo] na classe), então quem exclui é sempre um gestor — e, com a
            //     regra de autoexclusão acima, ele nunca é o excluído. Excluir qualquer outra
            //     pessoa portanto sempre deixa pelo menos ele. A contagem de gestores nunca
            //     chega a zero, e o invariante "sempre sobra alguém capaz de cadastrar acesso"
            //     já está garantido pela regra de cima, sozinha.
            // EN: There is deliberately NO separate "don't delete the last manager" rule here.
            //     I wrote one, and the test showed it could never fire: only Administrador and
            //     Gerente reach this screen (see [RequerCargo] on the class), so whoever
            //     deletes is always a manager — and, with the self-deletion rule above, never
            //     the one being deleted. Deleting anyone else therefore always leaves at least
            //     them. The manager count never reaches zero, and the invariant "someone
            //     capable of registering access always remains" is already guaranteed by the
            //     rule above, on its own.
            _context.Funcionarios.Remove(funcionario);
            await _context.SaveChangesAsync();
            TempData["Sucesso"] = "Funcionário removido.";
            return RedirectToAction(nameof(Index));
        }

        // PT: Lista para o dropdown opcional "Hóspede vinculado" nas telas de funcionário.
        // EN: List for the optional "Linked guest" dropdown on employee screens.
        private void CarregarListaHospedes(int? selecionado = null)
        {
            ViewData["HospedeId"] = new SelectList(
                _context.Hospedes.OrderBy(h => h.Nome), "HospedeId", "Nome", selecionado);
        }
    }
}
