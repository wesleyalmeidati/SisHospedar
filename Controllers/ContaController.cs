using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using SisHospedar.Data;
using SisHospedar.Models;
using SisHospedar.Services;

namespace SisHospedar.Controllers
{
    // PT: Fluxo de "esqueci minha senha" pede o e-mail (não o login) — mais fácil de
    //     lembrar, já que o login de funcionário é gerado automaticamente pelo sistema
    //     (ver FuncionarioController.GerarLoginUnicoAsync). Unificado como o login normal:
    //     tenta o e-mail digitado como funcionário e depois como hóspede, igual a
    //     AutenticacaoService.AutenticarAsync. Email é único por tabela (ver
    //     AppDbContext.OnModelCreating), então a busca nunca é ambígua dentro de uma
    //     mesma identidade. O link de redefinição vai por e-mail de verdade
    //     (IEmailSender/SmtpEmailSender), nunca aparece na tela. A confirmação mostra
    //     sempre a mesma mensagem genérica, exista ou não a conta com esse e-mail —
    //     evita revelar se um e-mail está cadastrado.
    // EN: "Forgot my password" flow asks for the email (not the login) — easier to
    //     remember, since an employee's login is auto-generated by the system (see
    //     FuncionarioController.GerarLoginUnicoAsync). Unified like normal login: tries
    //     the typed email as an employee, then as a guest, same as
    //     AutenticacaoService.AutenticarAsync. Email is unique per table (see
    //     AppDbContext.OnModelCreating), so the lookup is never ambiguous within a
    //     single identity. The reset link goes out by real email
    //     (IEmailSender/SmtpEmailSender), never shown on screen. The confirmation
    //     always shows the same generic message, whether or not an account with that
    //     email exists — avoids revealing whether an email is registered.
    public class ContaController : Controller
    {
        private readonly AppDbContext _context;
        private readonly UserManager<Funcionario> _userManagerFuncionario;
        private readonly UserManager<Hospede> _userManagerHospede;
        private readonly IEmailSender _emailSender;

        public ContaController(
            AppDbContext context,
            UserManager<Funcionario> userManagerFuncionario,
            UserManager<Hospede> userManagerHospede,
            IEmailSender emailSender)
        {
            _context = context;
            _userManagerFuncionario = userManagerFuncionario;
            _userManagerHospede = userManagerHospede;
            _emailSender = emailSender;
        }

        public IActionResult EsqueciSenha() => View();

        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> EsqueciSenha(string email)
        {
            if (string.IsNullOrWhiteSpace(email)) return View("EsqueciSenhaConfirmacao");

            var funcionario = await _context.Funcionarios.SingleOrDefaultAsync(f => f.Email == email);
            if (funcionario != null)
            {
                var token = await _userManagerFuncionario.GeneratePasswordResetTokenAsync(funcionario);
                await EnviarLinkAsync(funcionario.Email!, "funcionario", funcionario.FuncionarioId, token);
                return View("EsqueciSenhaConfirmacao");
            }

            var hospede = await _context.Hospedes.SingleOrDefaultAsync(h => h.Email == email);
            if (hospede != null && !string.IsNullOrEmpty(hospede.SenhaHash))
            {
                var token = await _userManagerHospede.GeneratePasswordResetTokenAsync(hospede);
                await EnviarLinkAsync(hospede.Email!, "hospede", hospede.HospedeId, token);
                return View("EsqueciSenhaConfirmacao");
            }

            // PT: Mesma tela, mesmo status — tanto faz se o e-mail não está cadastrado
            //     em nenhuma conta, se está numa conta de hóspede sem login/senha
            //     próprios, ou se o e-mail de redefinição acabou de ser enviado. Ver
            //     comentário da classe.
            // EN: Same screen, same status — doesn't matter whether the email isn't on
            //     any account, belongs to a guest with no login/password of their own,
            //     or the reset email was just sent. See the class-level comment.
            return View("EsqueciSenhaConfirmacao");
        }

        private async Task EnviarLinkAsync(string destinatario, string tipo, int id, string token)
        {
            var link = Url.Action(nameof(RedefinirSenha), "Conta", new { tipo, id, token }, Request.Scheme)!;
            var corpo = $"""
                <p>Você pediu a redefinição da sua senha no SisHospedar.</p>
                <p><a href="{link}">Clique aqui para escolher uma nova senha</a></p>
                <p>Se você não pediu isso, pode ignorar este e-mail.</p>
                """;
            await _emailSender.EnviarAsync(destinatario, "Redefinição de senha - SisHospedar", corpo);
        }

        public async Task<IActionResult> RedefinirSenha(string tipo, int id, string token)
        {
            if (!await ContaExisteAsync(tipo, id)) return NotFound();

            ViewData["Tipo"] = tipo;
            ViewData["Id"] = id;
            ViewData["Token"] = token;
            return View();
        }

        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> RedefinirSenha(string tipo, int id, string token, string novaSenha)
        {
            var resultado = string.Equals(tipo, "funcionario", StringComparison.OrdinalIgnoreCase)
                ? await RedefinirAsync(_userManagerFuncionario, id, token, novaSenha)
                : await RedefinirAsync(_userManagerHospede, id, token, novaSenha);

            if (resultado == null) return NotFound();

            if (resultado.Succeeded)
            {
                TempData["Sucesso"] = "Senha redefinida com sucesso. Faça login com a nova senha.";
                return RedirectToAction("Login", "Home");
            }

            foreach (var erro in resultado.Errors)
                ModelState.AddModelError("", erro.Description);

            ViewData["Tipo"] = tipo;
            ViewData["Id"] = id;
            ViewData["Token"] = token;
            return View();
        }

        private static async Task<IdentityResult?> RedefinirAsync<TEntity>(
            UserManager<TEntity> userManager, int id, string token, string novaSenha)
            where TEntity : class
        {
            var conta = await userManager.FindByIdAsync(id.ToString());
            return conta == null ? null : await userManager.ResetPasswordAsync(conta, token, novaSenha);
        }

        private async Task<bool> ContaExisteAsync(string tipo, int id) =>
            string.Equals(tipo, "funcionario", StringComparison.OrdinalIgnoreCase)
                ? await _userManagerFuncionario.FindByIdAsync(id.ToString()) != null
                : await _userManagerHospede.FindByIdAsync(id.ToString()) != null;
    }
}
