using System.Net;
using Microsoft.EntityFrameworkCore;
using SisHospedar.Models;

namespace SisHospedar.Tests;

// PT: O que estes testes protegem não é uma tela, é uma promessa: "sua escolha fica
//     guardada". Ela atravessa um redirect, um POST de login e outro redirect — três
//     lugares onde o returnUrl pode se perder sem quebrar nada visivelmente. Era
//     exatamente isso que acontecia antes: o parâmetro era gerado pelo handler de cookie e
//     nenhuma ação de login o lia, então o hóspede entrava e caía em "Minha Conta", sem a
//     reserva e sem explicação.
// EN: What these tests protect isn't a screen, it's a promise: "your choice is saved". It
//     travels through a redirect, a login POST and another redirect — three places where
//     returnUrl can be dropped without anything visibly breaking. That's exactly what used
//     to happen: the parameter was generated by the cookie handler and no login action read
//     it, so the guest signed in and landed in "My Account", with no booking and no
//     explanation.
public class ReservaFluxoAnonimoTests : TestesIntegracaoBase
{
    public ReservaFluxoAnonimoTests(CustomWebApplicationFactory factory) : base(factory) { }

    // PT: O header Location vem relativo quando o redirect parte do nosso código
    //     (Redirect/RedirectToAction) e absoluto quando parte do handler de cookie. Uri
    //     .AbsolutePath lança em URI relativa, então a comparação precisa tolerar as duas
    //     formas — foi exatamente nisso que estes testes tropeçaram primeiro.
    // EN: The Location header is relative when the redirect comes from our own code
    //     (Redirect/RedirectToAction) and absolute when it comes from the cookie handler.
    //     Uri.AbsolutePath throws on a relative URI, so the comparison has to tolerate both
    //     shapes — which is exactly what these tests tripped on first.
    private static string CaminhoDe(HttpResponseMessage resposta)
    {
        var destino = resposta.Headers.Location!;
        var texto = destino.IsAbsoluteUri ? destino.AbsolutePath : destino.ToString();
        var interrogacao = texto.IndexOf('?');
        return interrogacao >= 0 ? texto[..interrogacao] : texto;
    }

    private async Task<int> CriarApartamentoAsync(StatusApartamento status = StatusApartamento.Disponivel)
    {
        var id = 0;
        await Factory.UsandoContextoAsync(async db =>
        {
            var apartamento = new Apartamento
            {
                Numero = $"A{Guid.NewGuid():N}"[..9],
                Capacidade = 2,
                ValorDiaria = 200m,
                Status = status
            };
            db.Apartamentos.Add(apartamento);
            await db.SaveChangesAsync();
            id = apartamento.ApartamentoId;
        });
        return id;
    }

    private async Task<(string login, string senha)> CriarHospedeComContaAsync()
    {
        var sufixo = Guid.NewGuid().ToString("N")[..8];
        var login = $"h{sufixo}";
        var client = CriarCliente();

        // PT: Cria pelo fluxo real de cadastro para a conta nascer com hash e SecurityStamp
        //     corretos — inserir direto no banco daria uma conta que não consegue logar.
        // EN: Created through the real sign-up flow so the account gets a proper hash and
        //     SecurityStamp — inserting straight into the database would produce an account
        //     that can't sign in.
        var resposta = await PostComAntiforgeryAsync(client, "/Cliente/Registrar", "/Cliente/Registrar",
            new Dictionary<string, string>
            {
                ["Nome"] = "Hospede Fluxo",
                ["Cpf"] = GerarCpf(),
                ["Telefone"] = "(41) 90000-0000",
                ["DataNascimento"] = "1990-01-01",
                ["Email"] = $"{login}@exemplo.com",
                ["Login"] = login,
                ["senha"] = "Senha123"
            });

        Assert.Equal(HttpStatusCode.Redirect, resposta.StatusCode);
        return (login, "Senha123");
    }

    // PT: CPF sintético com dígitos verificadores calculados de verdade — CpfValidoAttribute
    //     roda no cadastro e recusaria um número inventado.
    // EN: A synthetic CPF with genuinely calculated check digits — CpfValidoAttribute runs on
    //     sign-up and would reject a made-up number.
    private static string GerarCpf()
    {
        var aleatorio = new Random();
        var digitos = new int[11];
        for (var i = 0; i < 9; i++) digitos[i] = aleatorio.Next(0, 9);

        for (var posicao = 9; posicao < 11; posicao++)
        {
            var soma = 0;
            for (var i = 0; i < posicao; i++) soma += digitos[i] * (posicao + 1 - i);
            var resto = soma % 11;
            digitos[posicao] = resto < 2 ? 0 : 11 - resto;
        }

        return string.Concat(digitos);
    }

    [Fact]
    public async Task Anonimo_AbreOFormularioDeReservaSemLogin()
    {
        var client = CriarCliente();

        var resposta = await client.GetAsync("/Reserva/Create");

        // PT: Antes isto era 302 para o login. A mudança inteira começa aqui: deixar a
        //     pessoa ver o que está reservando antes de pedir conta.
        // EN: This used to be a 302 to login. The whole change starts here: letting the
        //     person see what they're booking before asking for an account.
        Assert.Equal(HttpStatusCode.OK, resposta.StatusCode);
    }

    [Fact]
    public async Task Anonimo_AoEnviar_VaiParaLoginCarregandoAEscolha()
    {
        var apartamentoId = await CriarApartamentoAsync();
        var entrada = DateTime.Today.AddDays(10).ToString("yyyy-MM-dd");
        var saida = DateTime.Today.AddDays(13).ToString("yyyy-MM-dd");
        var client = CriarCliente();

        var resposta = await PostComAntiforgeryAsync(client, "/Reserva/Create", "/Reserva/Create",
            new Dictionary<string, string>
            {
                ["ApartamentoId"] = apartamentoId.ToString(),
                ["DataEntrada"] = entrada,
                ["DataSaidaPrevista"] = saida
            });

        Assert.Equal(HttpStatusCode.Redirect, resposta.StatusCode);
        var destino = resposta.Headers.Location!.ToString();

        Assert.Contains("/Cliente/Login", destino);
        // A escolha inteira precisa estar no retorno, senão ela se perde no login.
        Assert.Contains("returnUrl", destino, StringComparison.OrdinalIgnoreCase);
        Assert.Contains(apartamentoId.ToString(), Uri.UnescapeDataString(destino));
        Assert.Contains(entrada, Uri.UnescapeDataString(destino));
        Assert.Contains(saida, Uri.UnescapeDataString(destino));
    }

    [Fact]
    public async Task DepoisDoLogin_VoltaParaAReservaComOsDadosPreenchidos()
    {
        var apartamentoId = await CriarApartamentoAsync();
        var (login, senha) = await CriarHospedeComContaAsync();
        var entrada = DateTime.Today.AddDays(20).ToString("yyyy-MM-dd");
        var saida = DateTime.Today.AddDays(22).ToString("yyyy-MM-dd");

        var client = CriarCliente();
        var retorno = $"/Reserva/Create?apartamentoId={apartamentoId}&entrada={entrada}&saida={saida}";

        var resposta = await PostComAntiforgeryAsync(client, "/Cliente/Login", "/Cliente/Login",
            new Dictionary<string, string>
            {
                ["login"] = login,
                ["senha"] = senha,
                ["returnUrl"] = retorno
            });

        Assert.Equal(HttpStatusCode.Redirect, resposta.StatusCode);

        // PT: O coração da mudança. Cair em /Cliente/MinhaConta aqui significa que o
        //     returnUrl foi ignorado e a reserva se perdeu — o comportamento antigo.
        // EN: The heart of the change. Landing on /Cliente/MinhaConta here means returnUrl
        //     was ignored and the booking was lost — the old behavior.
        Assert.Equal("/Reserva/Create", CaminhoDe(resposta));

        var formulario = await client.GetStringAsync(retorno);
        Assert.Contains(entrada, formulario);
        Assert.Contains(saida, formulario);
    }

    [Fact]
    public async Task Login_NaoAceitaRetornoParaOutroDominio()
    {
        var (login, senha) = await CriarHospedeComContaAsync();
        var client = CriarCliente();

        var resposta = await PostComAntiforgeryAsync(client, "/Cliente/Login", "/Cliente/Login",
            new Dictionary<string, string>
            {
                ["login"] = login,
                ["senha"] = senha,
                ["returnUrl"] = "https://exemplo-malicioso.com/phishing"
            });

        // PT: returnUrl vem da URL, então é entrada do usuário. Sem Url.IsLocalUrl, a tela
        //     de login do próprio site viraria trampolim de phishing: a pessoa digita a
        //     senha aqui e é jogada em outro domínio logo depois.
        // EN: returnUrl comes from the URL, so it's user input. Without Url.IsLocalUrl, the
        //     site's own login screen would become a phishing springboard: the person types
        //     their password here and is thrown to another domain right after.
        Assert.Equal(HttpStatusCode.Redirect, resposta.StatusCode);
        Assert.DoesNotContain("exemplo-malicioso", resposta.Headers.Location!.ToString());
    }

    [Fact]
    public async Task Anonimo_ApartamentoIndisponivel_AvisaAntesDePedirCadastro()
    {
        var apartamentoId = await CriarApartamentoAsync(StatusApartamento.Ocupado);
        var client = CriarCliente();

        var resposta = await PostComAntiforgeryAsync(client, "/Reserva/Create", "/Reserva/Create",
            new Dictionary<string, string>
            {
                ["ApartamentoId"] = apartamentoId.ToString(),
                ["DataEntrada"] = DateTime.Today.AddDays(4).ToString("yyyy-MM-dd"),
                ["DataSaidaPrevista"] = DateTime.Today.AddDays(6).ToString("yyyy-MM-dd")
            });

        // PT: Mandar a pessoa criar conta para só no fim descobrir que o quarto acabou seria
        //     a pior ordem possível. O aviso vem antes do cadastro.
        // EN: Sending someone off to create an account only to discover at the end that the
        //     room is gone would be the worst possible order. The warning comes before sign-up.
        Assert.Equal(HttpStatusCode.OK, resposta.StatusCode);
        var html = await resposta.Content.ReadAsStringAsync();

        // PT: Trecho sem acento de propósito. A mensagem vem do ModelState e é renderizada
        //     pelo asp-validation-summary, ou seja, é valor dinâmico — e o Razor codifica
        //     acentos como entidades HTML ("n&#xE3;o est&#xE1;"). Texto estático da própria
        //     View não passa por isso, o que torna a diferença fácil de não perceber.
        // EN: An accent-free fragment on purpose. The message comes from ModelState and is
        //     rendered by asp-validation-summary, i.e. it's a dynamic value — and Razor
        //     encodes accents as HTML entities ("n&#xE3;o est&#xE1;"). Static text in the
        //     View itself doesn't go through that, which makes the difference easy to miss.
        Assert.Contains("Escolha outro", html);
    }

    [Fact]
    public async Task FluxoCompleto_AnonimoEscolheLogaEConcluiAReserva()
    {
        var apartamentoId = await CriarApartamentoAsync();
        var (login, senha) = await CriarHospedeComContaAsync();
        var entrada = DateTime.Today.AddDays(30);
        var saida = DateTime.Today.AddDays(33);

        var client = CriarCliente();

        // 1. Anônimo escolhe e envia.
        var redirecionamento = await PostComAntiforgeryAsync(client, "/Reserva/Create", "/Reserva/Create",
            new Dictionary<string, string>
            {
                ["ApartamentoId"] = apartamentoId.ToString(),
                ["DataEntrada"] = entrada.ToString("yyyy-MM-dd"),
                ["DataSaidaPrevista"] = saida.ToString("yyyy-MM-dd")
            });
        var retorno = Uri.UnescapeDataString(redirecionamento.Headers.Location!.ToString());
        var apenasCaminho = retorno[retorno.IndexOf("/Reserva", StringComparison.Ordinal)..];

        // 2. Entra na conta levando o retorno.
        var aposLogin = await PostComAntiforgeryAsync(client, "/Cliente/Login", "/Cliente/Login",
            new Dictionary<string, string>
            {
                ["login"] = login,
                ["senha"] = senha,
                ["returnUrl"] = apenasCaminho
            });
        Assert.Equal("/Reserva/Create", CaminhoDe(aposLogin));

        // 3. Confirma no formulário que voltou preenchido.
        var conclusao = await PostComAntiforgeryAsync(client, apenasCaminho, "/Reserva/Create",
            new Dictionary<string, string>
            {
                ["ApartamentoId"] = apartamentoId.ToString(),
                ["DataEntrada"] = entrada.ToString("yyyy-MM-dd"),
                ["DataSaidaPrevista"] = saida.ToString("yyyy-MM-dd")
            });
        Assert.Equal(HttpStatusCode.Redirect, conclusao.StatusCode);

        await Factory.UsandoContextoAsync(async db =>
        {
            var reserva = await db.Reservas
                .FirstOrDefaultAsync(r => r.ApartamentoId == apartamentoId && r.Status == StatusReserva.Pendente);
            Assert.NotNull(reserva);
            Assert.Equal(entrada.Date, reserva!.DataEntrada.Date);
        });
    }
}
